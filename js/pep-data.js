/* ---- PEP 专栏进度（与 GS 相互独立）----
   Store.d.pep = { lv: 当前册 id, done: { 单元id: { t, stars, pct } } } */
function pepEnsure() { if (!Store.d.pep) Store.d.pep = { lv: 'pep3a', done: {} }; if (!Store.d.pep.done) Store.d.pep.done = {}; }
function pepActiveLevelId() { pepEnsure(); if (PEP_LEVELS.some(l => l.id === Store.d.pep.lv)) return Store.d.pep.lv; return 'pep3a'; }
function pepSetActiveLevel(id) { pepEnsure(); if (PEP_LEVELS.some(l => l.id === id)) Store.d.pep.lv = id; }
function pepUnitDone(uid) { pepEnsure(); return !!Store.d.pep.done[uid]; }
function pepMarkDone(uid, pct, stars) {
  pepEnsure();
  const old = Store.d.pep.done[uid] || {};
  Store.d.pep.done[uid] = { t: Date.now(), stars: Math.max(stars || 0, old.stars || 0), pct: Math.max(pct || 0, old.pct || 0) };
  Store.save();
}
function pepLevelProgress(lv) {
  pepEnsure();
  const us = lv.units.filter(u => u.kind !== 'appendix');
  const n = us.filter(u => Store.d.pep.done[u.id]).length;
  return n + '/' + us.length;
}
function pepAllWordCount() { let n = 0; PEP_LEVELS.forEach(l => l.units.forEach(u => (u.words || []).forEach(() => n++))); return n; }
